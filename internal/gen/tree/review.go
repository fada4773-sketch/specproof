// The steps of tree-review_gen.md, in the order of the workflow. Each run
// of apitest-gen tree writes the sections of its steps and keeps the
// others.
const (
	ReviewTree     = "tree"
	ReviewFetch    = "fetch"
	ReviewScenario = "scenario"
	ReviewRun      = "run"
	ReviewUpdate   = "update"
)

var reviewSteps = []string{ReviewTree, ReviewFetch, ReviewScenario, ReviewRun, ReviewUpdate}

var reviewTitles = map[string]string{
	ReviewTree:     "Tree (tree.yaml)",
	ReviewFetch:    "Fetch (tree-data_gen.yaml)",
	ReviewScenario: "Scenario (tree-scenario_gen.yaml)",
	ReviewRun:      "Run (tree run)",
	ReviewUpdate:   "Update (tree run -update)",
}

// ReviewDoc is tree-review_gen.md: a section per step of the workflow, a
// status table and the next command on top.
type ReviewDoc struct {
	// Spec, SpecVersion and File name the files the commands use.
	Spec, SpecVersion, File string
	sections                map[string]*reviewSection
	fresh                   map[string]bool
}

type reviewSection struct {
	summary, outdated, body string
	failed                  bool
}

var specRE = regexp.MustCompile(`<!-- tree:spec \| (.*?) \| (.*?) -->`)

var sectionRE = regexp.MustCompile(`<!-- tree:(\w+) \| ([^\n]*?) \| ([^\n]*?) \| ([^\n]*?) -->\n(?s:(.*?))<!-- /tree:(\w+) -->`)

// LoadReview reads the review of an earlier run; a missing file (or one
// of an older form) gives an empty review.
func LoadReview(path string) *ReviewDoc {
	d := &ReviewDoc{sections: map[string]*reviewSection{}, fresh: map[string]bool{}}
	b, err := os.ReadFile(path)
	if err != nil {
		return d
	}
	if m := specRE.FindStringSubmatch(string(b)); m != nil {
		d.Spec, d.SpecVersion = m[1], m[2]
	}
	for _, m := range sectionRE.FindAllStringSubmatch(string(b), -1) {
		if m[1] != m[6] || !slices.Contains(reviewSteps, m[1]) {
			continue
		}
		d.sections[m[1]] = &reviewSection{failed: m[2] == "failed", summary: m[3], outdated: m[4], body: m[5]}
	}
	return d
}

// Has reports whether the review holds the section of a step.
func (d *ReviewDoc) Has(step string) bool { return d.sections[step] != nil }

// Set writes the section of a step: a one-line summary and the body.
func (d *ReviewDoc) Set(step, summary, body string, failed bool) {
	d.sections[step] = &reviewSection{summary: oneLine(summary), body: body, failed: failed}
	d.fresh[step] = true
}

// Outdate marks the sections of the steps after step that this run did not
// write: what step changed makes them stale.
func (d *ReviewDoc) Outdate(step, why string) {
	i := slices.Index(reviewSteps, step)
	for _, s := range reviewSteps[i+1:] {
		d.Mark(s, why)
	}
}

// Mark marks the section of a step as outdated unless this run wrote it.
func (d *ReviewDoc) Mark(step, why string) {
	if sec := d.sections[step]; sec != nil && !d.fresh[step] {
		sec.outdated = oneLine(why)
	}
}

func oneLine(s string) string {
	s = strings.NewReplacer("\n", " ", "|", "/", "-->", "->").Replace(s)
	return strings.TrimSpace(s)
}

// Render writes the review: status, next command, the sections in the
// order of the steps.
func (d *ReviewDoc) Render() string {
	var b strings.Builder
	b.WriteString("# Review: tree\n\n")
	b.WriteString("Generated by \"apitest-gen tree\"; each step writes its section and keeps the others.\n")
	if d.Spec != "" {
		fmt.Fprintf(&b, "<!-- tree:spec | %s | %s -->\nSpec %s", oneLine(d.Spec), oneLine(d.SpecVersion), d.Spec)
		if d.SpecVersion != "" {
			fmt.Fprintf(&b, " (version %s)", d.SpecVersion)
		}
		fmt.Fprintf(&b, " · %s\n", d.File)
	}
	b.WriteString("\n## Status\n\n| Step | State | Summary |\n|---|---|---|\n")
	for i, s := range reviewSteps {
		state, summary := "open", ""
		if sec := d.sections[s]; sec != nil {
			state, summary = "done", sec.summary
			if sec.failed {
				state = "failed"
			}
			if sec.outdated != "" {
				state = "outdated"
			}
		}
		fmt.Fprintf(&b, "| %d. %s | %s | %s |\n", i+1, reviewTitles[s], state, cell(summary))
	}
	fmt.Fprintf(&b, "\n**Next:** %s\n", d.next())
	for i, s := range reviewSteps {
		sec := d.sections[s]
		if sec == nil {
			continue
		}
		state := "done"
		if sec.failed {
			state = "failed"
		}
		fmt.Fprintf(&b, "\n<!-- tree:%s | %s | %s | %s -->\n", s, state, sec.summary, sec.outdated)
		fmt.Fprintf(&b, "## %d. %s\n\n", i+1, reviewTitles[s])
		if sec.outdated != "" {
			fmt.Fprintf(&b, "> **Outdated:** %s\n\n", sec.outdated)
		}
		body := strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(sec.body), fmt.Sprintf("## %d. %s", i+1, reviewTitles[s])))
		if strings.HasPrefix(body, "> **Outdated:**") {
			// the mark of an earlier render
			if _, rest, ok := strings.Cut(body, "\n"); ok {
				body = strings.TrimSpace(rest)
			} else {
				body = ""
			}
		}
		b.WriteString(body)
		fmt.Fprintf(&b, "\n<!-- /tree:%s -->\n", s)
	}
	return b.String()
}

// next is the command (or task) the review proposes next.
func (d *ReviewDoc) next() string {
	spec, file := d.Spec, d.File
	if spec == "" {
		spec = "<openapi.yaml>"
	}
	if file == "" {
		file = "tree.yaml"
	}
	tree := fmt.Sprintf("apitest-gen tree -spec %s -file %s", spec, file)
	run := fmt.Sprintf("apitest-gen tree run -spec %s -file %s -base-url <empty instance> -token-env <NAME>", spec, file)
	stale := func(s string) bool { sec := d.sections[s]; return sec == nil || sec.outdated != "" }
	switch {
	case d.sections[ReviewTree] == nil:
		return "propose the tree:\n\n```\n" + tree + "\n```\n"
	case stale(ReviewFetch):
		return "check tree.yaml (section 1: pick, where, write, params), then fetch the records from a stage:\n\n```\n" +
			tree + " -base-url <stage> -token-env <NAME>\n```\n"
	case stale(ReviewScenario):
		return "build the scenario from the records fetched before:\n\n```\n" + tree + "\n```\n"
	case stale(ReviewRun):
		return "check the seed and the gaps (section 3), then run the scenario against an empty instance; -update writes the golden snapshot and the examples:\n\n```\n" +
			run + " -update\n```\n"
	case d.sections[ReviewRun].failed:
		return "fix the failed steps (section 4: the instance, tree.yaml or the API), then run again:\n\n```\n" + run + "\n```\n"
	case stale(ReviewUpdate) || d.sections[ReviewUpdate].failed:
		return "write the golden snapshot and the examples:\n\n```\n" + run + " -update\n```\n"
	}
	return "done. Review the diff of the spec (examples) and the golden snapshot, commit them with tree.yaml and the scenario; CI runs:\n\n```\n" + run + "\n```\n"
}

// FileSection is the section of tree.yaml: scope, the nodes with what they
// pick and write, the params without value, what is not proposed, the
// changes of this run and what to check before the fetch.
func FileSection(t *Tree, changes []Change, proposed bool) (string, string) {
	var b strings.Builder
	nodes, writes := 0, 0
	var seed, picked []string
	conds := 0
	t.Walk(func(n *Node) {
		if n.IsRequire {
			return
		}
		nodes++
		for _, k := range n.Kinds() {
			if w := n.Write[k]; w.None && k == WriteCreate {
				seed = append(seed, n.Name)
			} else if !w.Off && !w.Gone {
				writes++
			}
		}
		if len(n.Where)+len(n.WhereAny)+len(n.Require) > 0 {
			conds++
		}
		if n.Pick.N > 0 && !n.Pick.First {
			picked = append(picked, n.Name)
		}
	})
	unset := t.UnsetParams()
	how := "up to date with the spec"
	switch {
	case proposed:
		how = "proposed from the spec"
	case len(changes) > 0:
		how = "merged with the spec"
	}
	summary := fmt.Sprintf("%s: %d nodes, %d writes", how, nodes, writes)
	if len(changes) > 0 {
		summary += fmt.Sprintf(", %d changes", len(changes))
	}
	if len(unset) > 0 {
		summary += fmt.Sprintf(", %d params without value", len(unset))
	}
	fmt.Fprintf(&b, "tree.yaml %s.", how)
	if sc := scopeText(t.Scope); sc != "" {
		fmt.Fprintf(&b, " Scope: %s.", sc)
	}
	fmt.Fprintf(&b, " %d nodes, %d writes.\n", nodes, writes)
	if len(changes) > 0 {
		fmt.Fprintf(&b, "\n### Changes of this run (%d)\n\n| Where | What |\n|---|---|\n", len(changes))
		for _, c := range changes {
			fmt.Fprintf(&b, "| %s | %s |\n", cell(c.Where), cell(c.What))
		}
	}
	b.WriteString("\n### Nodes\n\n")
	var walk func([]*Node, int)
	walk = func(list []*Node, depth int) {
		for _, n := range list {
			fmt.Fprintf(&b, "%s- %s\n", strings.Repeat("  ", depth), nodeLine(n))
			walk(n.Each, depth+1)
		}
	}
	walk(t.Roots, 0)
	if len(unset) > 0 {
		fmt.Fprintf(&b, "\n### Params without value (%d)\n\nNo record of the tree gives them; set them under params at the top of tree.yaml.\nThe nodes that use them are left out of the fetch.\n\n| Param | Used by |\n|---|---|\n", len(unset))
		for _, p := range unset {
			used := t.ParamNotes[p]
			if used == "" {
				used = strings.Join(paramUsers(t, p), ", ")
			}
			fmt.Fprintf(&b, "| %s | %s |\n", p, cell(used))
		}
	}
	if len(t.Ignore) > 0 {
		fmt.Fprintf(&b, "\n### Not proposed: ignore (%d)\n\n| Operation | Why |\n|---|---|\n", len(t.Ignore))
		for _, op := range t.Ignore {
			fmt.Fprintf(&b, "| %s | %s |\n", cell(op), cell(t.IgnoreNotes[op]))
		}
	}
	b.WriteString("\n### Check before the fetch\n\n")
	if len(unset) > 0 {
		fmt.Fprintf(&b, "- set the params: %s\n", strings.Join(unset, ", "))
	}
	if len(picked) > 0 {
		fmt.Fprintf(&b, "- %s pick at random (seed %d); give keys (`pick: [..]`) for fixed records\n", strings.Join(picked, ", "), t.Seed)
	}
	if conds > 0 {
		fmt.Fprintf(&b, "- %d nodes have where/require; the reason is the comment after each condition\n", conds)
	}
	if len(seed) > 0 {
		fmt.Fprintf(&b, "- create: none on %s: the empty instance must hold these records (seed)\n", strings.Join(seed, ", "))
	}
	b.WriteString("- every write: the call and its values (`.field` of the record, `<node>.field` of a node above)\n")
	return summary, b.String()
}

func scopeText(sc Scope) string {
	var parts []string
	if len(sc.Tags) > 0 {
		parts = append(parts, "tags "+strings.Join(sc.Tags, ", "))
	}
	if len(sc.ExcludeTags) > 0 {
		parts = append(parts, "without tags "+strings.Join(sc.ExcludeTags, ", "))
	}
	if len(sc.ExcludeOps) > 0 {
		parts = append(parts, "without "+strings.Join(sc.ExcludeOps, ", "))
	}
	if sc.Deps {
		parts = append(parts, "with deps")
	}
	return strings.Join(parts, "; ")
}

// nodeLine is a node in the outline: name, call, pick, conditions, writes.
func nodeLine(n *Node) string {
	parts := []string{fmt.Sprintf("`%s` %s", n.Name, n.Call)}
	if n.Comment != "" {
		parts[0] += " (" + n.Comment + ")"
	}
	switch p := n.Pick; {
	case len(p.Keys) > 0:
		var ks []string
		for _, k := range p.Keys {
			ks = append(ks, text(k))
		}
		parts = append(parts, "pick ["+strings.Join(ks, ", ")+"]")
	case p.All:
		parts = append(parts, "pick all")
	case p.First:
		parts = append(parts, fmt.Sprintf("first %d", p.N))
	case p.N > 0:
		parts = append(parts, fmt.Sprintf("pick %d", p.N))
	}
	var cs, rs []string
	for _, c := range n.Where {
		cs = append(cs, c.Field+" "+testText(c.Test))
	}
	if len(n.WhereAny) > 0 {
		cs = append(cs, fmt.Sprintf("any of %d", len(n.WhereAny)))
	}
	if len(cs) > 0 {
		parts = append(parts, "where "+strings.Join(cs, ", "))
	}
	for _, r := range n.Require {
		rs = append(rs, r.Name)
	}
	if len(rs) > 0 {
		parts = append(parts, "require "+strings.Join(rs, ", "))
	}
	if k := n.Kinds(); len(k) > 0 {
		if w := n.Write[WriteCreate]; w != nil && w.None {
			k[0] = "create: none"
		}
		parts = append(parts, "write: "+strings.Join(k, ", "))
	}
	if n.Off {
		parts = append(parts, "off")
	}
	if n.Gone {
		parts = append(parts, "gone from the spec")
	}
	return strings.Join(parts, " · ")
}

// testText writes the test of a where clause: one of a list as [A, B].
func testText(v any) string {
	l, ok := v.([]any)
	if !ok {
		if s, isStrings := v.([]string); isStrings {
			return "[" + strings.Join(s, ", ") + "]"
		}
		return text(v)
	}
	var out []string
	for _, x := range l {
		out = append(out, text(x))
	}
	return "[" + strings.Join(out, ", ") + "]"
}

// paramUsers are the nodes and writes that use "$name".
func paramUsers(t *Tree, name string) []string {
	uses := func(vals ...map[string]any) bool {
		for _, m := range vals {
			for _, v := range m {
				if p, ok := ParamRef(v); ok && p == name {
					return true
				}
			}
		}
		return false
	}
	var out []string
	t.Walk(func(n *Node) {
		if uses(n.Path, n.Query, n.Header) {
			out = append(out, n.Name)
		}
		for _, k := range n.Kinds() {
			if w := n.Write[k]; uses(w.Path, w.Query, w.Header) {
				out = append(out, n.Name+".write."+k)
			}
		}
	})
	return out
}

// FetchSection is the section of a fetch: the records per node and the
// notes.
func FetchSection(d *Data, stale []string) (string, string) {
	var b strings.Builder
	summary := fmt.Sprintf("%d records, %d requests", len(d.Records), d.Requests)
	fmt.Fprintf(&b, "%d records from %s (%d requests, GET only).\n", len(d.Records), d.Source, d.Requests)
	var order []*Node
	per := map[*Node][]*Record{}
	for _, r := range d.Records {
		if per[r.Node] == nil {
			order = append(order, r.Node)
		}
		per[r.Node] = append(per[r.Node], r)
	}
	if len(order) > 0 {
		b.WriteString("\n### Records per node\n\n| Node | Records | Keys |\n|---|---|---|\n")
		for _, n := range order {
			var keys []string
			for _, r := range per[n] {
				if k := KeyText(r.Value, keyOf(n)); k != "" && !slices.Contains(keys, k) {
					keys = append(keys, k)
				}
			}
			if len(keys) > 5 {
				keys = append(keys[:5], "…")
			}
			fmt.Fprintf(&b, "| %s | %d | %s |\n", n.Name, len(per[n]), cell(strings.Join(keys, ", ")))
		}
	}
	if len(d.Notes) > 0 {
		summary += fmt.Sprintf(", %d notes", len(d.Notes))
		fmt.Fprintf(&b, "\n### Notes (%d)\n\n", len(d.Notes))
		for _, n := range d.Notes {
			fmt.Fprintf(&b, "- %s\n", n)
		}
	}
	if len(stale) > 0 {
		summary += fmt.Sprintf(", %d of nodes gone", len(stale))
		fmt.Fprintf(&b, "\n### Records of nodes the tree no longer has (%d)\n\nFetch again with -base-url: %s\n", len(stale), strings.Join(stale, ", "))
	}
	return summary, b.String()
}

// ScenarioSection is the section of the built scenario: its steps by kind,
// the seed the instance must hold, the decisions and gaps.
func ScenarioSection(built *Built) (string, string) {
	var b strings.Builder
	steps := 0
	if built.Scenario != nil {
		steps = len(built.Scenario.Steps)
	}
	summary := fmt.Sprintf("%d steps, %d records created, %d of the seed, %d notes", steps, len(built.Created), len(built.Seeds), len(built.Notes))
	fmt.Fprintf(&b, "%d steps, %d records created.\n", steps, len(built.Created))
	if built.Scenario != nil && steps > 0 {
		counts := map[string]int{}
		var kinds []string
		for _, st := range built.Scenario.Steps {
			k := stepKind(st.ID, st.Expect)
			if counts[k] == 0 {
				kinds = append(kinds, k)
			}
			counts[k]++
		}
		b.WriteString("\n| Steps | Count |\n|---|---|\n")
		for _, k := range kinds {
			fmt.Fprintf(&b, "| %s | %d |\n", k, counts[k])
		}
	}
	if len(built.Seeds) > 0 {
		fmt.Fprintf(&b, "\n### Seed: the instance must hold these records (%d)\n\n", len(built.Seeds))
		b.WriteString("The scenario reads them by the values of the stage and creates none of them\n(create: none, or no create in the spec). Put them into the seed of the test instance.\n\n")
		b.WriteString("| Record | Request | Key |\n|---|---|---|\n")
		for _, r := range built.Seeds {
			fmt.Fprintf(&b, "| %s | %s | %s |\n", r.ID, cell(r.Request), cell(KeyText(r.Value, keyOf(r.Node))))
		}
	}
	if len(built.Notes) > 0 {
		notes := append([]Note(nil), built.Notes...)
		sort.SliceStable(notes, func(i, j int) bool { return notes[i].Step < notes[j].Step })
		fmt.Fprintf(&b, "\n### Decisions and gaps (%d)\n\n| Step | What | Why |\n|---|---|---|\n", len(notes))
		for _, n := range notes {
			fmt.Fprintf(&b, "| %s | %s | %s |\n", cell(n.Step), cell(n.What), cell(n.Why))
		}
	}
	return summary, b.String()
}

// stepKind sorts a step of the scenario by its id: create, read, update …
func stepKind(id string, expect int) string {
	last := id[strings.LastIndex(id, ".")+1:]
	switch {
	case strings.HasSuffix(id, ".unauthorized"):
		return "without token (401)"
	case strings.Contains(id, ".read.afterDelete"):
		return "read after delete (404)"
	case strings.Contains(id, ".read.after"):
		return "read after a change"
	case last == WriteCreate:
		return "create"
	case KindBase(last) == WriteUpdate || KindBase(last) == WritePatch:
		return "update, patch"
	case KindBase(last) == WriteDelete:
		return "delete"
	case expect/100 != 2 && expect != 0:
		return "error"
	}
	return "read, list, action"
}

// RunSection is the section of a run: the verdict, the counts and every
// step that did not pass.
func RunSection(res *apitest.Result, baseURL string, unique bool) (string, string, bool) {
	var b strings.Builder
	verdict := "PASSED"
	if res.Failed {
		verdict = "FAILED"
	}
	var counts []string
	for _, s := range []apitest.Status{apitest.StatusPassed, apitest.StatusFailed, apitest.StatusSchemaViolation, apitest.StatusExampleMismatch,
		apitest.StatusDataMismatch, apitest.StatusError, apitest.StatusDeviation, apitest.StatusTolerated, apitest.StatusNotBuildable, apitest.StatusSkipped} {
		if n := res.Summary.Counts[s]; n > 0 {
			counts = append(counts, fmt.Sprintf("%d %s", n, s))
		}
	}
	summary := fmt.Sprintf("%s: %d steps (%s)", verdict, res.Summary.Total, strings.Join(counts, ", "))
	fmt.Fprintf(&b, "%s against %s", summary, baseURL)
	if unique {
		b.WriteString(", with -unique")
	}
	b.WriteString(".\n")
	var bad []apitest.CaseResult
	for _, c := range res.Cases {
		if c.Status != apitest.StatusPassed && c.Status != apitest.StatusSkipped {
			bad = append(bad, c)
		}
	}
	if len(bad) > 0 {
		fmt.Fprintf(&b, "\n### Steps that did not pass (%d)\n\n| Step | Status | Message |\n|---|---|---|\n", len(bad))
		for _, c := range bad {
			fmt.Fprintf(&b, "| %s | %s | %s |\n", cell(c.Name), c.Status, cell(c.Message))
		}
	}
	if res.Report != "" {
		fmt.Fprintf(&b, "\nReport: %s\n", res.Report)
	}
	return summary, b.String(), res.Failed
}

func cell(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "|", "\\|"), "\n", " ")
}
